"""Generate a measured mesh-vs-formula proof and a synthetic calibration example."""
from pathlib import Path
import json
import math
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))


def measurements():
    from karigar.packs.jewellery import geometry as g
    rows=[]
    for inner,width,thickness in [(15,3,1.5),(18,4,2),(22,5,2.5)]:
        g.clear_scene()
        obj=g.band(inner,width,thickness,'flat')
        a,b=thickness/2,width/2
        area=4*a*b*math.gamma(1+1/6)**2/math.gamma(1+2/6)
        # The engine's flat profile is a superellipse, not a rectangular annulus.
        exact=2*math.pi*(inner/2+a)*area
        rows.append((f'Flat-profile band, inner {inner} mm',g.mesh_volume(obj),exact,
                     'Pappus: 2πR × 4ab Γ(7/6)² / Γ(4/3)'))
    g.clear_scene()
    disc=g.cylinder((0,0,0),10,0,1.2,segs=256)
    rows.append(('Disc, radius 10 mm, thickness 1.2 mm',g.mesh_volume(disc),math.pi*10**2*1.2,'πr²h'))
    g.clear_scene()
    torus=g.torus(10,1,steps=256,segs=128)
    rows.append(('Round wire ring, major radius 10 mm, wire radius 1 mm',g.mesh_volume(torus),2*math.pi**2*10,'2π²Rr²'))
    g.clear_scene()
    return [{'shape':name,'mesh_mm3':mesh,'formula_mm3':exact,'error_pct':abs(mesh-exact)/exact*100,'formula':formula}
            for name,mesh,exact,formula in rows]


def calibration():
    from karigar.core.calibration import CalibrationStore
    with tempfile.TemporaryDirectory() as directory:
        store=CalibrationStore(Path(directory)/'calibration.json')
        before=store.loss_pct('sample')
        for actual in (9.6,9.62,9.58):store.record('sample',10,actual)
        return {'label':'Synthetic demonstration, not real casting evidence',
                'before_loss_pct':before,'after_loss_pct':store.loss_pct('sample'),
                'next_10g_cast_finished_prediction_g':10*(1-store.loss_pct('sample')/100),
                'tolerance':store.tolerance('sample')}


def main():
    rows=measurements()
    assert all(r['error_pct']<0.5 for r in rows), rows
    result={'measurements':rows,'calibration':calibration()}
    (ROOT/'docs/weight-proof.json').write_text(json.dumps(result,indent=2))
    text='# Weight maths proof\n\nGenerated by `scripts/weight_proof.py` using the real Blender mesh volume function. This proves mesh arithmetic, not finished casting accuracy.\n\n'
    text+='The engine’s flat band is a rounded superellipse cross-section; comparing it to a rectangular annulus would be an incorrect reference. Its exact volume follows Pappus’s centroid theorem.\n\n'
    text+='| Reference shape | Mesh mm³ | Exact mm³ | Error | Formula |\n|---|---:|---:|---:|---|\n'
    for r in rows:text+=f"| {r['shape']} | {r['mesh_mm3']:.4f} | {r['formula_mm3']:.4f} | {r['error_pct']:.4f}% | {r['formula']} |\n"
    c=result['calibration']
    text+=f"\nSynthetic calibration: three 10 g designs finish at 9.60, 9.62 and 9.58 g. Expected loss changes from {c['before_loss_pct']:.1f}% to {c['after_loss_pct']:.2f}%; the next 10 g casting predicts {c['next_10g_cast_finished_prediction_g']:.2f} g finished. No production calibration file is modified.\n"
    (ROOT/'docs/weight-proof.md').write_text(text)
    print(text)


if __name__=='__main__':main()

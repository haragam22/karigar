// Records a silent, real-UI backup walkthrough. Requires the isolated local preview.
import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
const require=createRequire(import.meta.url);
const puppeteer=require(process.env.HALLMARK_PUPPETEER || 'puppeteer-core');
const base=process.env.KARIGAR_PREVIEW_URL || 'http://127.0.0.1:8080';
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
await mkdir('out',{recursive:true});
const browser=await puppeteer.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage();
await page.setViewport({width:1440,height:900,deviceScaleFactor:1});
await page.goto(base+'/console/',{waitUntil:'networkidle0'});
await page.type('#token',process.env.KARIGAR_PREVIEW_TOKEN||'local-demo-owner');
await page.click('#login-form button');
await page.waitForSelector('#shell:not([hidden])');
await page.waitForFunction(()=>document.querySelector('model-viewer')?.loaded);
const ffmpegPath=execFileSync('.venv/bin/python',['-c','import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())'],{encoding:'utf8'}).trim();
const recorder=await page.screencast({path:'out/karigar-backup.webm',ffmpegPath,fps:15,format:'webm'});
console.log('Recording real sample-data studio');
await pause(20000);
await page.goto(base+'/console/#catalogue',{waitUntil:'networkidle0'});
await page.evaluate(()=>Array.from(document.images).forEach(i=>i.loading='eager'));
await pause(7000);await page.evaluate(()=>scrollBy({top:600,behavior:'smooth'}));await pause(6500);await page.evaluate(()=>scrollBy({top:650,behavior:'smooth'}));await pause(6500);
console.log('Showing variants, measured gold and sourced quote');
await page.goto(base+'/console/#orders',{waitUntil:'networkidle0'});
await page.click('tr:has(.badge.done) td a');
await pause(10000);await page.evaluate(()=>document.querySelector('.section.split')?.scrollIntoView({behavior:'smooth'}));await pause(17000);await page.evaluate(()=>scrollBy({top:600,behavior:'smooth'}));await pause(8000);
await page.goto(base+'/console/#viewer',{waitUntil:'networkidle0'});
await page.click('#spin-view');await pause(20000);
await page.goto(base+'/console/#workshop',{waitUntil:'networkidle0'});await pause(15000);
console.log('Showing a real impossible-request response');
await page.goto(base+'/console/#demo',{waitUntil:'networkidle0'});
await page.type('#chat-text','22K ring, size 14, under 1.2 g, with a 1 ct diamond',{delay:25});
await page.click('#chat-form .primary');
await page.waitForFunction(()=>!document.querySelector('#chat-form .primary').disabled,{timeout:60000});
await page.waitForFunction(()=>document.querySelector('.message.assistant')?.textContent.includes('2.36')||document.querySelector('.message.assistant')?.textContent.includes('lightest'),{timeout:10000});
await pause(15000);
await page.screenshot({path:'out/refusal-complete.png'});
await recorder.stop();await browser.close();
// Hold the verified actual result screen at the end, avoiding dropped final compositor frames.
execFileSync(ffmpegPath,['-y','-loglevel','error','-i','out/karigar-backup.webm','-loop','1','-framerate','15','-t','20','-i','out/refusal-complete.png','-filter_complex','[0:v]fps=15,format=yuv420p,setsar=1,setpts=PTS-STARTPTS[a];[1:v]format=yuv420p,setsar=1,setpts=PTS-STARTPTS[b];[a][b]concat=n=2:v=1:a=0[v]','-map','[v]','-an','-r','15','-c:v','libx264','-crf','20','-preset','fast','-movflags','+faststart','out/karigar-backup.mp4']);
await writeFile('out/karigar-backup.vtt',`WEBVTT\n\n00:00.000 --> 00:20.000\nSample workshop: a real engine-generated floral ring, not a stock mockup.\n\n00:20.000 --> 00:40.000\nOriginal parametric catalogue, measured at lighter, balanced and statement proportions.\n\n00:40.000 --> 01:15.000\nInspect variants, predicted metal weight, tolerance, sourced quote and production files.\n\n01:15.000 --> 01:35.000\nRotate the actual GLB. Design scale and casting shrinkage are kept distinct.\n\n01:35.000 --> 01:50.000\nThe workshop learns loss from actual finished weights.\n\n01:50.000 --> 02:20.000\nAn impossible request gets a measured constraint and alternatives.\n`);
console.log('Saved out/karigar-backup.mp4, out/karigar-backup.webm and out/karigar-backup.vtt');
